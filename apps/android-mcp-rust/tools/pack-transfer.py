#!/usr/bin/env python3
"""Audit an existing single-EXE ZIP and archive an explicit Rust source allowlist."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import io
import json
import os
from pathlib import Path
import struct
import subprocess
import tempfile
import zipfile
import zlib
import gzip

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[1]
FIXED_TIME = (1980, 1, 1, 0, 0, 0)
ROOT_FILES = (
    "Cargo.toml", "Cargo.lock", "build.rs", "package.json", "rustfmt.toml",
    ".gitignore", ".cargo/config.toml", "README.md", "README.zh_CN.md",
)
SOURCE_DIRS = {
    "src": {".rs"}, "assets": {".html", ".css", ".js", ".json"},
    "tools": {".mjs", ".py"}, "docs": {".md", ".json"},
}
FIXTURES = (
    "tests/fixtures/jpeg.mjs", "tests/fixtures/loopback-test-only.pem",
    "tests/fixtures/loopback-test-only.pfx", "tests/fixtures/README.md",
    "tools/fixtures/operator-text-cases.js",
    "tools/fixtures/operator-recovery-cases.js",
)
SUPPORT_FILES = ("apps/android-mcp/src/fixtures/jpeg.ts", "apps/android-mcp/src/http.ts",
                 "apps/android-mcp/tests/operator.test.mjs", "apps/android-mcp/tests/screen-channel.test.mjs")
USB_HELPER_FILES = tuple("tools/usb-driver/" + name for name in (
    "windows.c", "protocol.c", "protocol.h", "transfer.c", "transfer.h",
    "hardware.c", "hardware.h", "test-protocol.c", "test-transfer.c", "test-hardware.c", "README.md",
))
SOURCE_README = b"""# Rust source snapshot

This ZIP preserves apps/android-mcp-rust and its explicitly named public test
fixtures, including a sibling JPEG fixture and public UI/channel regression
fixtures (their server source is read only to validate its runtime version).
It does not contain the rest of the monorepo, generated builds, local device
configuration, logs, caches, Cargo/npm dependencies, or credentials.

On Windows, install Rust 1.87+, Visual Studio C++ MSVC build tools, and Node 24/npm 11.
The standalone EXE does not require Node, but every Cargo build prepares assets
with the exact esbuild version pinned in package.json. In this source snapshot:
  cd apps/android-mcp-rust
  npm install --workspaces=false --include=dev
  cargo check --locked
  cargo test --locked
  cargo build --locked --release

Cargo downloads the versions pinned in Cargo.lock; the Windows configuration
retains static CRT linkage. Build assets use parser-based JS/CSS minification,
conservative HTML indentation removal, and compact JSON; generated bytes and
minifier version participate in the build ID. QDD_NODE can name an explicit Node
executable. Optional official-SDK tests use the pinned package.json dependency;
npm dependencies are not bundled. Public loopback TLS test keys are documented in
tests/fixtures/README.md and are not installation-machine secrets.

SOURCE-MANIFEST.json lists every source entry and hash. ZIP entries are sorted,
use fixed timestamps and permissions, and preserve exact source bytes. Matching
Python/zlib versions reproduce the same archive from identical input files.

The tools/usb-driver directory contains the separate native Windows USB ZIP
downloader and its production parser/transfer/hardware-ID regressions. Build it
with x64 MinGW-w64 GCC and Node: set QDD_USB_CC to the compiler executable (or put
gcc on PATH), then run node tools/usb-driver/build.mjs from apps/android-mcp-rust.
Its runtime needs only Windows system DLLs. The helper only saves a verified ZIP;
it does not automatically extract/run the main console or stop an existing one.
"""


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def json_bytes(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def check(condition: bool, message: str) -> None:
    if not condition:
        raise RuntimeError(message)


def source_entries() -> dict[str, bytes]:
    paths = [ROOT / name for name in ROOT_FILES + FIXTURES + USB_HELPER_FILES]
    for directory, suffixes in SOURCE_DIRS.items():
        paths.extend(path for path in (ROOT / directory).rglob("*")
                     if path.is_file() and path.suffix in suffixes)
    paths.extend(REPO / name for name in SUPPORT_FILES)
    entries = {}
    for path in sorted(set(paths)):
        check(path.is_file() and not path.is_symlink(), f"Missing/linked source: {path.name}")
        resolved = path.resolve()
        name = path.relative_to(REPO).as_posix()
        try:
            resolved.relative_to(REPO)
        except ValueError as error:
            raise RuntimeError("Source escapes repository") from error
        check(not any(part in {"build", "target", "node_modules", "__pycache__"}
                      for part in Path(name).parts), "Generated directory in source allowlist")
        check(path.name not in {"qdd-android.json", ".env", "config.json"},
              "Local configuration in source allowlist")
        entries[name] = path.read_bytes()
    return entries


def source_build_id(entries: dict[str, bytes]) -> str:
    """Reproduce build.rs assets/identity and bind its inputs to the source ZIP."""
    prefix = ROOT.relative_to(REPO).as_posix() + "/"
    with tempfile.TemporaryDirectory(prefix="qdd-rust-source-assets-") as temporary:
        generated = Path(temporary).resolve()
        check(generated.parent == Path(tempfile.gettempdir()).resolve(), "Unexpected asset temporary directory")
        process = subprocess.run([os.environ.get("QDD_NODE", "node"), str(ROOT / "tools/prepare-assets.mjs"),
                                  "--out-dir", str(generated)], cwd=ROOT, capture_output=True,
                                 timeout=30, creationflags=0x08000000 if os.name == "nt" else 0)
        check(process.returncode == 0, "Asset/identity reproduction failed; install pinned npm dependencies")
        report = json.loads((generated / "asset-build.json").read_text(encoding="utf-8"))
        for item in report["identityInputs"]:
            contents = entries.get(prefix + item["path"])
            check(contents is not None and len(contents) == item["bytes"] and sha(contents) == item["sha256"],
                  "Archived source differs from regenerated build inputs")
        return report["buildId"]


def deterministic_zip(entries: dict[str, bytes]) -> bytes:
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, contents in sorted(entries.items()):
            info = zipfile.ZipInfo(name, FIXED_TIME)
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, contents, compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
    return output.getvalue()


def extract_entry_bytes(packed: bytes, entry: zipfile.ZipInfo, size: int, central_start: int) -> bytes:
    """Verify the actual stored stream; ZipExtFile clips output to file_size."""
    offset = entry.header_offset
    check(0 <= offset <= len(packed) - 30, "ZIP local header is out of range")
    local = struct.unpack_from("<4s5H3I2H", packed, offset)
    signature, _, flags, method, _, _, crc, compressed, unpacked, name_size, extra_size = local
    name_start = offset + 30
    data_start = name_start + name_size + extra_size
    data_end = data_start + entry.compress_size
    check(signature == b"PK\x03\x04" and flags == entry.flag_bits and flags & 0x800
          and method == entry.compress_type and method in (zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED)
          and packed[name_start:name_start + name_size] == entry.orig_filename.encode("utf-8")
          and crc == entry.CRC and compressed == entry.compress_size and unpacked == size
          and data_start <= data_end <= central_start <= len(packed),
          "ZIP local entry does not match its central header")
    segment = packed[data_start:data_end]
    if method == zipfile.ZIP_STORED:
        result = segment
    else:
        decoder = zlib.decompressobj(-15)
        result = decoder.decompress(segment, size + 1)
        check(decoder.eof and not decoder.unconsumed_tail and not decoder.unused_data,
              "ZIP DEFLATE stream is incomplete, oversized or has trailing bytes")
    check(len(result) == size and zlib.crc32(result) == entry.CRC,
          "ZIP actual extracted size or CRC mismatch")
    return result


def verify_executable_zip(directory: Path, manifest: dict) -> dict:
    executable = directory / manifest["executable"]
    check(executable.parent == directory and executable.name == "设备操作台.exe", "Unexpected EXE filename")
    payload = executable.read_bytes()
    packed = (directory / "设备操作台.zip").read_bytes()
    check(len(payload) == manifest["bytes"] and sha(payload) == manifest["sha256"], "EXE identity mismatch")
    check(len(packed) == manifest["zipBytes"] and sha(packed) == manifest["zipSha256"], "ZIP identity mismatch")
    with zipfile.ZipFile(io.BytesIO(packed)) as archive:
        infos = archive.infolist()
        # ZipInfo.filename truncates at NUL; the original ZIP name must also match.
        check(len(infos) == 1 and infos[0].filename == executable.name
              and infos[0].orig_filename == executable.name and "\0" not in infos[0].orig_filename
              and not infos[0].is_dir() and (infos[0].external_attr >> 16) & 0o170000 != 0o120000,
              "ZIP must contain exactly the named EXE, without configuration")
        check(not infos[0].flag_bits & 1 and infos[0].file_size == len(payload), "Encrypted/invalid EXE entry")
        unpacked = extract_entry_bytes(packed, infos[0], len(payload), archive.start_dir)
    check(unpacked == payload, "Extracted EXE bytes differ")
    temporary = Path(tempfile.mkdtemp(prefix="qdd-rust-transfer-")).resolve()
    check(temporary.parent == Path(tempfile.gettempdir()).resolve(), "Unexpected extraction directory")
    extracted = temporary / executable.name
    try:
        extracted.write_bytes(unpacked)
        check(sha(extracted.read_bytes()) == manifest["sha256"], "Extracted file hash mismatch")
        process = subprocess.run([str(extracted), "--self-test"], cwd=temporary, capture_output=True,
                                 timeout=15, creationflags=0x08000000 if os.name == "nt" else 0)
        check(process.returncode == 0, "Extracted EXE self-test failed")
        result = json.loads(process.stdout)
        check(result.get("status") == "ok" and result.get("buildId") == manifest["buildId"], "Self-test identity mismatch")
        check(sorted(path.name for path in temporary.iterdir()) == [executable.name], "Self-test generated unexpected files")
    finally:
        extracted.unlink(missing_ok=True)
        temporary.rmdir()  # Flat verified extraction only; no recursive deletion.
    return {"status": "pass", "entries": [executable.name], "crcVerified": True,
            "originalFilenameVerified": True, "linkedEntryRejected": True,
            "rawCompressedStreamVerified": True,
            "extractedSha256": sha(unpacked), "selfTestBuildId": result["buildId"],
            "configurationIncluded": False, "serviceStarted": False, "inputSent": False,
            "exeBytes": len(payload), "zipBytes": len(packed), "zipSha256": sha(packed),
            "zipPercentOfExe": round(len(packed) / len(payload) * 100, 4),
            "savedPercent": round((1 - len(packed) / len(payload)) * 100, 4)}


def verify_usb_helper(path: Path, entries: dict[str, bytes]) -> dict:
    helper = json.loads(path.read_bytes())
    check(helper["platform"] == "win32-x64" and helper["executable"] == "设备USB下载器.exe"
          and helper["protocol"] == "QDDDRV/1", "Unexpected USB helper identity")
    payload = (path.parent / helper["executable"]).read_bytes()
    packed = (path.parent / helper["gzip"]["file"]).read_bytes()
    check(0 < len(payload) <= 128 * 1024 and len(payload) == helper["bytes"]
          and sha(payload) == helper["sha256"], "USB helper EXE identity mismatch")
    check(len(packed) == helper["gzip"]["bytes"] and sha(packed) == helper["gzip"]["sha256"]
          and gzip.decompress(packed) == payload, "USB helper gzip identity mismatch")
    prefix = ROOT.relative_to(REPO).as_posix() + "/"
    for item in helper["sourceInputs"]:
        contents = entries.get(prefix + item["path"])
        check(contents is not None and len(contents) == item["bytes"] and sha(contents) == item["sha256"],
              "USB helper source differs from its frozen manifest")
    return {key: helper[key] for key in ("platform", "executable", "bytes", "sha256", "protocol", "gzip", "sourceInputs")}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact-dir", type=Path, required=True)
    parser.add_argument("--source-output-dir", type=Path,
                        help="Write only the new source archive/audits here; leave the input artifact directory untouched")
    parser.add_argument("--usb-helper-manifest", type=Path,
                        help="Optionally bind the separately frozen native USB helper to this source snapshot")
    args = parser.parse_args()
    directory = args.artifact_dir.resolve()
    check(directory.is_dir(), "Artifact directory must already exist")
    output_directory = args.source_output_dir.resolve() if args.source_output_dir else directory
    check(not output_directory.is_symlink(), "Refusing linked source output directory")
    output_directory.mkdir(parents=True, exist_ok=True)
    manifest_bytes = (directory / "manifest.json").read_bytes()
    manifest = json.loads(manifest_bytes)
    exe_audit = verify_executable_zip(directory, manifest)
    entries = source_entries()
    # Recreate the generated asset bytes/tool identity before binding this source snapshot.
    check(source_build_id(entries) == manifest["buildId"], "Current source does not match this EXE build ID")
    listing = [{"path": name, "bytes": len(data), "sha256": sha(data)} for name, data in sorted(entries.items())]
    source_manifest = {"schemaVersion": 1, "artifactBuildId": manifest["buildId"],
                       "artifactSha256": manifest["sha256"], "files": listing,
                       "excluded": ["build", "target", "node_modules", "qdd-android.json", "local settings", "logs"],
                       "supportFiles": list(SUPPORT_FILES), "publicTlsFixtures": list(FIXTURES[1:3])}
    if args.usb_helper_manifest:
        source_manifest["usbHelper"] = verify_usb_helper(args.usb_helper_manifest.resolve(), entries)
    entries["SOURCE-README.md"] = SOURCE_README
    entries["SOURCE-MANIFEST.json"] = json_bytes(source_manifest)
    source_zip = deterministic_zip(entries)
    check(source_zip == deterministic_zip(entries), "Source ZIP is not reproducible")
    with zipfile.ZipFile(io.BytesIO(source_zip)) as archive:
        check(archive.testzip() is None and set(archive.namelist()) == set(entries), "Source ZIP entries/CRC mismatch")
        check(all(archive.read(name) == data for name, data in entries.items()), "Source ZIP byte mismatch")
    source_audit = {"status": "pass", "archive": "android-mcp-rust-source.zip", "bytes": len(source_zip),
                    "sha256": sha(source_zip), "sourceFiles": len(listing), "archiveEntries": len(entries),
                    "uncompressedBytes": sum(map(len, entries.values())), "reproducible": True,
                    "fixedTimestamp": list(FIXED_TIME), "python": os.sys.version.split()[0], "zlib": zlib.ZLIB_VERSION,
                    "allEntryHashesVerified": True, "crcVerified": True, "configurationIncluded": False}
    source_audit["savedPercent"] = round((1 - len(source_zip) / source_audit["uncompressedBytes"]) * 100, 4)
    report = {"timestamp": datetime.now(timezone.utc).isoformat(), "status": "pass",
              "artifactBuildId": manifest["buildId"], "executableZip": exe_audit, "sourceZip": source_audit}
    for filename, contents in {source_audit["archive"]: source_zip,
                               "android-mcp-rust-source-manifest.json": json_bytes(source_manifest),
                               "transfer-compression-audit.json": json_bytes(report)}.items():
        output = output_directory / filename
        check(output.name not in {manifest["executable"], "设备操作台.zip", "manifest.json"}, "Refusing to overwrite input artifact")
        check(not output.is_symlink(), "Refusing linked output")
        temporary = output.with_name(output.name + ".tmp")
        with temporary.open("xb") as target:
            target.write(contents)
        temporary.replace(output)
    check((directory / "manifest.json").read_bytes() == manifest_bytes, "Input manifest changed")
    check(sha((directory / manifest["executable"]).read_bytes()) == manifest["sha256"], "Input EXE changed")
    check(sha((directory / "设备操作台.zip").read_bytes()) == manifest["zipSha256"], "Input EXE ZIP changed")
    os.sys.stdout.reconfigure(encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
