import {readFile,writeFile} from 'node:fs/promises';
const sources={
 CAMERA_SKILL_MARKDOWN:new URL('../skills/haik-camera/SKILL.md',import.meta.url),
 CAMERA_CAPTURE_MARKDOWN:new URL('../skills/haik-camera/references/capture.md',import.meta.url),
 CAMERA_SURVEY_MARKDOWN:new URL('../skills/haik-camera/references/survey.md',import.meta.url),
 CAMERA_SURVEY_SCRIPT:new URL('../skills/haik-camera/scripts/camera-survey.mjs',import.meta.url),
};
let output='// Generated by scripts/build-mcp-skill.mjs. Edit skills/haik-camera instead.\n';
for(const [name,url] of Object.entries(sources)){
 const text=(await readFile(url,'utf8')).replace(/\r\n/g,'\n');
 if(/\bTODO\b|\[INSERT/i.test(text))throw new Error('Unfinished skill scaffold');
 output+=`export const ${name} = ${JSON.stringify(text)};\n`;
}
const target=new URL('../lib/mcp-skill-data.mjs',import.meta.url);
if(process.argv.includes('--check')){
 if(await readFile(target,'utf8')!==output)throw new Error('Embedded MCP skill is stale; run npm run skill:build');
 console.log('Embedded MCP skill is current.');
}else{await writeFile(target,output);console.log('Built embedded MCP skill.');}
