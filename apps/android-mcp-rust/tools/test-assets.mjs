import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import test from "node:test";
import vm from "node:vm";
import { ASSET_NAMES, ROOT, buildId, minifyHtml, prepareAssets } from "./prepare-assets.mjs";
import { bootSettingsHtml } from "./settings-fixture.mjs";

test("HTML preserves inline spacing, attributes, pre/textarea and inert script bodies", async () => {
  const source = '<main>\n  <div data-x=">">\n  <p><span>A</span> \n <span>B</span></p>\n  </div>\n<pre>\n  A  B\n</prefix> tail</pre><textarea>\n A &amp; B\n</textarea><script type="application/json">{ "space": " A  B " }</script></main>';
  const output = await minifyHtml(source);
  assert.ok(output.length < source.length);
  for (const preserved of ['data-x=">"', '<span>A</span> \n <span>B</span>', '<pre>\n  A  B\n</prefix> tail</pre>', '<textarea>\n A &amp; B\n</textarea>', '{ "space": " A  B " }']) assert.ok(output.includes(preserved), preserved);
  assert.match(await minifyHtml('<script>let text="İ";</script>'), /İ/);
});

test("all generated assets are deterministic, smaller, UTF8 and preserve DOM/schema contracts", async () => {
  const first = await prepareAssets(), second = await prepareAssets();
  assert.equal(first.buildId, second.buildId);
  assert.deepEqual(first.manifestBytes, second.manifestBytes);
  assert.equal(first.manifest.minifier.version, "0.28.2");
  for (const name of ASSET_NAMES) {
    const original = await readFile(join(ROOT, "assets", name), "utf8");
    const generated = first.assets.get(name).toString();
    assert.deepEqual(first.assets.get(name), second.assets.get(name));
    assert.ok(Buffer.byteLength(generated) < Buffer.byteLength(original), name);
    if (name.endsWith(".js")) new vm.Script(generated, { filename: name });
    if (name.endsWith(".html")) {
      const hooks = (html) => [...html.matchAll(/\b(?:id|class|aria-[\w-]+|src|href)="[^"]*"/g)].map((match) => match[0]);
      assert.deepEqual(hooks(generated), hooks(original), name);
    }
    if (name.endsWith(".json")) assert.deepEqual(JSON.parse(generated), JSON.parse(original));
  }
  assert.ok(first.assets.get("operator.js").toString().includes("页面已隐藏"));
  assert.ok(!first.assets.get("operator.js").toString().includes("\\u9875"));
});

test("identity changes for pipeline, minifier metadata and actual generated bytes", () => {
  const original = new Map([["tools/prepare-assets.mjs", Buffer.from("pipeline")], ["@generated/asset-manifest.json", Buffer.from('"0.28.2"')], ["@generated/assets/operator.js", Buffer.from("code")]]);
  const expected = buildId(original);
  assert.equal(expected, buildId(new Map([...original].reverse())));
  for (const name of original.keys()) {
    const changed = new Map(original); changed.set(name, Buffer.concat([changed.get(name), Buffer.from("changed")]));
    assert.notEqual(buildId(changed), expected);
  }
});

function bootSettings(template, data) {
  const payload = JSON.stringify(data).replaceAll("<", "\\u003c");
  const html = template.replaceAll("__QDD_SAVE_PATH__", "/fixture-save").replaceAll("__QDD_DISCOVER_PATH__", "/fixture-find").replace("__QDD_SETTINGS_DATA__", payload);
  return bootSettingsHtml(html);
}

test("minified settings inject exact configuration, safe problem text, discover and save behavior", async () => {
  const bundle = await prepareAssets();
  const problem = "</script><img src=x> &amp; __QDD_SAVE_PATH__ __QDD_DISCOVER_PATH__ __QDD_SETTINGS_DATA__\u2028\u2029";
  const data = { defaults: { ANDROID_SCREEN_URL: "http://192.168.1.5:8791", ESP_HOST: "192.168.1.8:3334", ESP_TCP_PORT: "3333", ANDROID_MCP_PORT: "8971", ESP_PORT: "COM6" }, ports: ["COM6"], problem, mcpUrl: "http://127.0.0.1:8971/mcp" };
  const { elements, requests, context, html } = bootSettings(bundle.assets.get("settings.html").toString(), data);
  assert.equal(elements.get("message").textContent, problem);
  assert.equal(elements.get("local-port").value, "8971");
  assert.equal(elements.get("mcp-address").textContent, data.mcpUrl);
  assert.equal(html.split("</script>").length, 2);
  await elements.get("form").onsubmit({ preventDefault() {} });
  assert.equal(requests[0].url, "/fixture-save");
  const body = JSON.parse(requests[0].options.body);
  assert.equal(body.ESP_HOST, "192.168.1.8"); assert.equal(body.ESP_TCP_PORT, 3333);
  assert.equal(body.ANDROID_MCP_PORT, "8971"); assert.equal(body.ANDROID_SCREEN_URL, data.defaults.ANDROID_SCREEN_URL);
  assert.equal(context.location.href, "http://127.0.0.1:8971/");
  elements.get("find").onclick();
  await new Promise(setImmediate);
  assert.equal(requests[1].url, "/fixture-find");
  assert.equal(elements.get("find").disabled, false);
});
