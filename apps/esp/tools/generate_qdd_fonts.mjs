import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = fileURLToPath(new URL("../", import.meta.url));
const upstream = "managed_components/lvgl__lvgl/scripts/built_in_font";
const source = join(root, upstream, "SourceHanSansSC-Normal.otf");
const assets = join(root, "assets/fonts");
const chinese = new Set();
for (const name of ["qdd_ui.c", "qdd_ui_model.c", "qdd_setup_model.c", "qdd_main.c"]) {
  for (const symbol of await readFile(join(root, "main", name), "utf8")) {
    if (symbol.codePointAt(0) > 127) chinese.add(symbol);
  }
}
const symbols = [...chinese].sort((a, b) => a.codePointAt(0) - b.codePointAt(0)).join("");
await mkdir(assets, { recursive: true });
await writeFile(join(assets, "qdd_glyphs.txt"), `${symbols}\n`);
await copyFile(join(root, upstream, "font_license/SourceHanSansSC/LICENSE.txt"), join(assets, "OFL-SourceHanSans.txt"));
const npmCli = process.env.npm_execpath ?? join(dirname(process.execPath), "node_modules/npm/bin/npm-cli.js");
const files = [];
for (const size of [14, 20]) {
  const output = `assets/fonts/qdd_cjk_${size}.c`;
  const args = ["--font", source, "--range", "0x20-0x7E", "--symbols", symbols,
    "--size", String(size), "--bpp", "4", "--format", "lvgl", "--no-compress", "--no-kerning",
    "--lv-font-name", `qdd_cjk_${size}`, "--lv-include", "lvgl.h", "--output", join(root, output)];
  const result = spawnSync(process.execPath, [npmCli, "exec", "--yes", "--package=lv_font_conv@1.5.3", "--", "lv_font_conv", ...args], { cwd: root, stdio: "inherit" });
  if (result.error || result.status !== 0) throw new Error(`Font conversion failed for ${size}px.`);
  let data = await readFile(join(root, output), "utf8");
  // Keep machine paths out of generated headers; all reproduction inputs are in the manifest.
  data = data.replace(/\s*Opts:.*\r?\n/, "\n * Generated by tools/generate_qdd_fonts.mjs; see qdd-fonts.json and OFL-SourceHanSans.txt.\n");
  data = `/* QDD CJK bitmap subset, derived from Source Han Sans SC.\n * Copyright 2014-2021 Adobe. Licensed under SIL OFL 1.1; see OFL-SourceHanSans.txt.\n */\n${data}`;
  data = data.replace(/\r\n?/g, "\n").trimEnd() + "\n";
  await writeFile(join(root, output), data);
  files.push({ path: output, size, bpp: 4, compressed: false, sha256: createHash("sha256").update(data).digest("hex") });
}
await writeFile(join(assets, "qdd-fonts.json"), JSON.stringify({
  source: "LVGL v9.5.0 scripts/built_in_font/SourceHanSansSC-Normal.otf",
  sourceUrl: "https://github.com/lvgl/lvgl/blob/v9.5.0/scripts/built_in_font/SourceHanSansSC-Normal.otf",
  sourceSha256: createHash("sha256").update(await readFile(source)).digest("hex"),
  license: "SIL OFL 1.1", converter: "lv_font_conv@1.5.3",
  characterInventory: "qdd_glyphs.txt plus printable ASCII U+0020..U+007E",
  chineseCodepoints: [...symbols].map((character) => character.codePointAt(0)), files,
}, null, 2) + "\n");
console.log(`Generated QDD 14/20px subsets: ${chinese.size} non-ASCII and 95 printable ASCII codepoints each.`);
